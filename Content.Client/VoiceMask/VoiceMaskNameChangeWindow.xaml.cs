using System.Linq;
using Content.Client.UserInterface.Controls;
using Content.Shared._Sunrise.TTS;
using Content.Shared.Speech;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client.VoiceMask;

[GenerateTypedNameReferences]
public sealed partial class VoiceMaskNameChangeWindow : FancyWindow
{
    [Dependency] private readonly IPrototypeManager _prototypeManager = default!; // Sunrise-Edit
    public Action<string>? OnNameChange;
    public Action<string?>? OnVerbChange;
    public Action<string>? OnVoiceSelected; // Sunrise-Edit
    public Action<string>? OnVoicePreview; // Sunrise-Edit

    private List<(string, string)> _verbs = new();
    private List<TTSVoicePrototype> _voiceList = new(); // Sunrise-Edit

    private string? _verb;

    public VoiceMaskNameChangeWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this); // Sunrise-Edit

        NameSelectorSet.OnPressed += _ =>
        {
            OnNameChange?.Invoke(NameSelector.Text);
        };

        SpeechVerbSelector.OnItemSelected += args =>
        {
            OnVerbChange?.Invoke((string?) args.Button.GetItemMetadata(args.Id));
            SpeechVerbSelector.SelectId(args.Id);
        };

        LoadVoiceList(_prototypeManager); // Sunrise-Edit
        SetupButtons(); // Sunrise-Edit
    }

    public void ReloadVerbs(IPrototypeManager proto)
    {
        foreach (var verb in proto.EnumeratePrototypes<SpeechVerbPrototype>())
        {
            _verbs.Add((Loc.GetString(verb.Name), verb.ID));
        }
        _verbs.Sort((a, b) => a.Item1.CompareTo(b.Item1));
    }

    public void AddVerbs()
    {
        SpeechVerbSelector.Clear();

        AddVerb(Loc.GetString("chat-speech-verb-name-none"), null);
        foreach (var (name, id) in _verbs)
        {
            AddVerb(name, id);
        }
    }

    private void AddVerb(string name, string? verb)
    {
        var id = SpeechVerbSelector.ItemCount;
        SpeechVerbSelector.AddItem(name);
        if (verb is {} metadata)
            SpeechVerbSelector.SetItemMetadata(id, metadata);

        if (verb == _verb)
            SpeechVerbSelector.SelectId(id);
    }

    // Sunrise-Start
    public void LoadVoiceList(IPrototypeManager proto)
    {
        _voiceList.Clear();
        _voiceList.AddRange(proto
            .EnumeratePrototypes<TTSVoicePrototype>()
            .Where(v => v.RoundStart)
            .OrderBy(v => Loc.GetString(v.Name)));
    }
        private void SetupButtons()
    {
        VoiceOptionButton.OnItemSelected += args =>
        {
            VoiceOptionButton.SelectId(args.Id);
            var voice = _voiceList[args.Id];
            OnVoiceSelected?.Invoke(voice.ID);
        };

        VoicePlayButton.OnPressed += _ =>
        {
            if (VoiceOptionButton.SelectedId != null)
            {
                var voice = _voiceList[VoiceOptionButton.SelectedId];
                OnVoicePreview?.Invoke(voice.ID);
            }
        };
    }
    // Sunrise-End

    public void UpdateState(string name, string voice, string? verb) // Sunrise-TTS
    {
        NameSelector.Text = name;
        _verb = verb;

        for (int id = 0; id < SpeechVerbSelector.ItemCount; id++)
        {
            if (string.Equals(verb, SpeechVerbSelector.GetItemMetadata(id)))
            {
                SpeechVerbSelector.SelectId(id);
                break;
            }
        }

        // Sunrise-Start
        VoiceOptionButton.Clear();

        var selectedIndex = 0;
        for (var i = 0; i < _voiceList.Count; i++)
        {
            var voiceProto = _voiceList[i];
            var nameProto = Loc.GetString(voiceProto.Name);

            VoiceOptionButton.AddItem(nameProto, i);

            if (voiceProto.ID == voice)
            {
                selectedIndex = i;
            }
        }

        if (_voiceList.Count > 0)
        {
            VoiceOptionButton.SelectId(selectedIndex);
        }
        // Sunrise-End
    }
}
