using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Client.UserInterface;
using Robust.Shared.Localization;
using Robust.Shared.Maths;
using Robust.Shared.Utility;

namespace Content.Client.UserInterface.Systems.Ghost.Controls.PlanetPrison;

[GenerateTypedNameReferences]
public sealed partial class PlanetPrisonRoleEntry : BoxContainer
{
    public event Action<PriorityLevel>? PrioritySelected;
    public event Action? LoadoutPressed;

    public enum PriorityLevel
    {
        Never,
        Low,
        Medium,
        High
    }

    private PriorityLevel _currentPriority = PriorityLevel.Never;
    public string RoleId { get; }
    private bool _isLocked = false;

    public PlanetPrisonRoleEntry(string roleId, string name, string description)
    {
        RoleId = roleId;
        RobustXamlLoader.Load(this);

        Title.Text = name;
        Description.SetMessage(FormattedMessage.FromMarkupPermissive(description));

        // Устанавливаем начальный приоритет "Никогда"
        _currentPriority = PriorityLevel.Never;
        UpdateButtonStates();

        NeverButton.OnPressed += _ => SetPriority(PriorityLevel.Never);
        LowButton.OnPressed += _ => SetPriority(PriorityLevel.Low);
        MediumButton.OnPressed += _ => SetPriority(PriorityLevel.Medium);
        HighButton.OnPressed += _ => SetPriority(PriorityLevel.High);
        LoadoutButton.OnPressed += _ => LoadoutPressed?.Invoke();
    }

    private void SetPriority(PriorityLevel priority)
    {
        _currentPriority = priority;
        UpdateButtonStates();
        PrioritySelected?.Invoke(priority);
    }


    public void SetSelectedPriority(PriorityLevel priority)
    {
        _currentPriority = priority;
        UpdateButtonStates();
    }

    private void UpdateButtonStates()
    {
        NeverButton.Disabled = _currentPriority == PriorityLevel.Never;
        LowButton.Disabled = _currentPriority == PriorityLevel.Low;
        MediumButton.Disabled = _currentPriority == PriorityLevel.Medium;
        HighButton.Disabled = _currentPriority == PriorityLevel.High;

        NeverButton.StyleClasses.Remove("ButtonSquareCaution");
        LowButton.StyleClasses.Remove("ButtonSquareCaution");
        MediumButton.StyleClasses.Remove("ButtonSquareCaution");
        HighButton.StyleClasses.Remove("ButtonSquareCaution");

        NeverButton.StyleClasses.Add("ButtonSquare");
        LowButton.StyleClasses.Add("ButtonSquare");
        MediumButton.StyleClasses.Add("ButtonSquare");
        HighButton.StyleClasses.Add("ButtonSquare");

        switch (_currentPriority)
        {
            case PriorityLevel.Never:
                NeverButton.StyleClasses.Remove("ButtonSquare");
                NeverButton.StyleClasses.Add("ButtonSquareCaution");
                break;
            case PriorityLevel.Low:
                LowButton.StyleClasses.Remove("ButtonSquare");
                LowButton.StyleClasses.Add("ButtonSquareCaution");
                break;
            case PriorityLevel.Medium:
                MediumButton.StyleClasses.Remove("ButtonSquare");
                MediumButton.StyleClasses.Add("ButtonSquareCaution");
                break;
            case PriorityLevel.High:
                HighButton.StyleClasses.Remove("ButtonSquare");
                HighButton.StyleClasses.Add("ButtonSquareCaution");
                break;
        }
    }

    public void ShowTakenStatus()
    {
        StatusLabel.Text = Loc.GetString("planet-prison-role-taken");
        StatusLabel.FontColorOverride = Color.Red;
        StatusLabel.Visible = true;
        DisableButtons();
    }

    public void ShowAssignedStatus()
    {
        StatusLabel.Text = Loc.GetString("planet-prison-role-assigned");
        StatusLabel.FontColorOverride = Color.Green;
        StatusLabel.Visible = true;
        DisableButtons();
    }

    public void HideStatus()
    {
        StatusLabel.Visible = false;
    }

    public void EnableButtons()
    {
        NeverButton.Disabled = false;
        LowButton.Disabled = false;
        MediumButton.Disabled = false;
        HighButton.Disabled = false;
    }

    public void DisableButtons()
    {
        NeverButton.Disabled = true;
        LowButton.Disabled = true;
        MediumButton.Disabled = true;
        HighButton.Disabled = true;
        UpdateButtonStates(); // Обновляем стили даже при блокировке
    }

    public void SetLocked(bool locked)
    {
        if (locked)
        {
            DisableButtons();
        }
        else
        {
            EnableButtons();
            // Переустанавливаем текущий приоритет, чтобы восстановить стили
            SetSelectedPriority(_currentPriority);
        }
    }

    public void LockRequirements(FormattedMessage requirements)
    {
        _isLocked = true;
        LockLabel.Text = Loc.GetString("role-timer-locked");

        var tooltip = new Tooltip();
        tooltip.SetMessage(requirements);
        LockStripe.TooltipSupplier = _ => tooltip;

        // Устанавливаем темный фон, как у счетчика участников
        if (LockStripe.PanelOverride == null)
        {
            var styleBox = new StyleBoxFlat { BackgroundColor = Color.FromHex("#202023") };
            LockStripe.PanelOverride = styleBox;
        }

        LockStripe.Visible = true;
        PriorityButtons.Visible = false;
        DisableButtons();
    }

    public void UnlockRequirements()
    {
        _isLocked = false;
        LockStripe.TooltipSupplier = null;
        LockStripe.Visible = false;
        PriorityButtons.Visible = true;
        EnableButtons();
        // Переустанавливаем текущий приоритет, чтобы восстановить стили
        SetSelectedPriority(_currentPriority);
    }

    public bool IsLocked => _isLocked;
}
