using Content.Client.PDA;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client.UserInterface.Systems.Ghost.Controls.PlanetPrison;

[GenerateTypedNameReferences]
public sealed partial class PlanetPrisonWindow : DefaultWindow
{
    public event Action? MapsTabPressed;
    public event Action? RolesTabPressed;

    public PlanetPrisonWindow()
    {
        RobustXamlLoader.Load(this);

        MapsTabButton.OnPressed += _ => SwitchToMapsTab();
        RolesTabButton.OnPressed += _ => SwitchToRolesTab();
    }

    private void SwitchToMapsTab()
    {
        MapsTabButton.IsCurrent = true;
        RolesTabButton.IsCurrent = false;
        MapsContainer.Visible = true;
        RolesContainer.Visible = false;
        MapsTabPressed?.Invoke();
    }

    private void SwitchToRolesTab()
    {
        MapsTabButton.IsCurrent = false;
        RolesTabButton.IsCurrent = true;
        MapsContainer.Visible = false;
        RolesContainer.Visible = true;
        RolesTabPressed?.Invoke();
    }

    public void ClearMaps()
    {
        MapsEntryContainer.RemoveAllChildren();
    }

    public void ClearRoles()
    {
        RolesEntryContainer.RemoveAllChildren();
    }

    public void AddMapEntry(Control entry)
    {
        MapsEntryContainer.AddChild(entry);
    }

    public void AddRoleEntry(Control entry)
    {
        RolesEntryContainer.AddChild(entry);
    }

    public int MapsEntryCount => MapsEntryContainer.ChildCount;
    public int RolesEntryCount => RolesEntryContainer.ChildCount;

    // Public accessors for priority counter elements
    public Label GetPriorityCounterLabel() => PriorityCounterLabel;
    public PanelContainer GetPriorityCounterPanel() => PriorityCounterPanel;
}
