using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Maths;
using Robust.Shared.Utility;

namespace Content.Client.UserInterface.Systems.Ghost.Controls.PlanetPrison;

[GenerateTypedNameReferences]
public sealed partial class PlanetPrisonMapEntry : BoxContainer
{
    public event Action<PriorityLevel>? PrioritySelected;

    public enum PriorityLevel
    {
        Never,
        Low,
        Medium,
        High
    }

    private PriorityLevel _currentPriority = PriorityLevel.Never;

    public PlanetPrisonMapEntry(string name, string description)
    {
        RobustXamlLoader.Load(this);

        Title.Text = name;
        Description.SetMessage(FormattedMessage.FromMarkupPermissive(description));

        // Устанавливаем начальный приоритет "Никогда"
        _currentPriority = PriorityLevel.Never;
        UpdateButtonStates();

        NeverButton.OnPressed += _ => SetPriority(PriorityLevel.Never);
        LowButton.OnPressed += _ => SetPriority(PriorityLevel.Low);
        MediumButton.OnPressed += _ => SetPriority(PriorityLevel.Medium);
        HighButton.OnPressed += _ => SetPriority(PriorityLevel.High);
    }

    private void SetPriority(PriorityLevel priority)
    {
        _currentPriority = priority;
        UpdateButtonStates();
        PrioritySelected?.Invoke(priority);
    }

    public void SetSelectedPriority(PriorityLevel priority)
    {
        _currentPriority = priority;
        UpdateButtonStates();
    }

    private void UpdateButtonStates()
    {
        // Сбрасываем все кнопки к обычному состоянию
        NeverButton.StyleClasses.Remove("ButtonSquarePressed");
        LowButton.StyleClasses.Remove("ButtonSquarePressed");
        MediumButton.StyleClasses.Remove("ButtonSquarePressed");
        HighButton.StyleClasses.Remove("ButtonSquarePressed");

        NeverButton.Disabled = false;
        LowButton.Disabled = false;
        MediumButton.Disabled = false;
        HighButton.Disabled = false;

        // Выделяем текущий выбранный приоритет
        switch (_currentPriority)
        {
            case PriorityLevel.Never:
                NeverButton.StyleClasses.Add("ButtonSquarePressed");
                NeverButton.Disabled = true; // Блокируем выбранную кнопку
                break;
            case PriorityLevel.Low:
                LowButton.StyleClasses.Add("ButtonSquarePressed");
                LowButton.Disabled = true; // Блокируем выбранную кнопку
                break;
            case PriorityLevel.Medium:
                MediumButton.StyleClasses.Add("ButtonSquarePressed");
                MediumButton.Disabled = true; // Блокируем выбранную кнопку
                break;
            case PriorityLevel.High:
                HighButton.StyleClasses.Add("ButtonSquarePressed");
                HighButton.Disabled = true; // Блокируем выбранную кнопку
                break;
        }
    }

    public void ShowTimer(int seconds)
    {
        TimerLabel.Text = $"({seconds})";
        TimerLabel.Visible = true;
    }

    public void HideTimer()
    {
        TimerLabel.Visible = false;
    }

    public void ShowVoteCount(int current, int required)
    {
        VoteCountLabel.Text = Loc.GetString("planet-prison-vote-count", ("current", current), ("required", required));
        VoteCountLabel.Visible = true;
    }

    public void HideVoteCount()
    {
        VoteCountLabel.Visible = false;
    }

    public void ShowLaunchingStatus()
    {
        StatusLabel.Text = Loc.GetString("planet-prison-launching");
        StatusLabel.FontColorOverride = Color.FromHex("#FFEB3B"); // Желтый цвет
        StatusLabel.Visible = true;
    }

    public void ShowLaunchedStatus()
    {
        StatusLabel.Text = Loc.GetString("planet-prison-launched");
        StatusLabel.FontColorOverride = Color.FromHex("#F44336"); // Красный цвет
        StatusLabel.Visible = true;
    }

    public void HideStatus()
    {
        StatusLabel.Visible = false;
    }

    public void DisableButtons()
    {
        NeverButton.Disabled = true;
        LowButton.Disabled = true;
        MediumButton.Disabled = true;
        HighButton.Disabled = true;
    }

    public void EnableButtons()
    {
        // Разблокируем все кнопки кроме текущего выбора
        NeverButton.Disabled = _currentPriority == PriorityLevel.Never;
        LowButton.Disabled = _currentPriority == PriorityLevel.Low;
        MediumButton.Disabled = _currentPriority == PriorityLevel.Medium;
        HighButton.Disabled = _currentPriority == PriorityLevel.High;
    }

    public PriorityLevel CurrentPriority => _currentPriority;
}
