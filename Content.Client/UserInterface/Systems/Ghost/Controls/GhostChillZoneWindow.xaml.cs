using Content.Shared._Sunrise.GhostChillZone;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.UserInterface.Systems.Ghost.Controls;


[GenerateTypedNameReferences]
public sealed partial class GhostChillZoneWindow : DefaultWindow
{

    public GhostChillZoneWindow()
    {
        RobustXamlLoader.Load(this);
    }

    protected override void Opened()
    {
        base.Opened();
        GhostChillZoneRequestButton.OnPressed += RequestSpawn;
    }

    public override void Close()
    {
        base.Close();
        GhostChillZoneRequestButton.OnPressed -= RequestSpawn;
    }

    private void RequestSpawn(BaseButton.ButtonEventArgs obj)
    {
        var net = IoCManager.Resolve<IEntityNetworkManager>();

        var msg = new GhostChillZoneSpawnRequest();

        net.SendSystemNetworkMessage(msg);

        Close();
    }
}
