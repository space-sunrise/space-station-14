using Content.Client.UserInterface.Controls;
using Content.Shared._Sunrise.Silicons.StationAi;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Sunrise.Silicons.StationAi;

[GenerateTypedNameReferences]
public sealed partial class StationAiBodyWindow : FancyWindow
{
    public event Action<NetEntity>? EnterBodyAction;
    public event Action? ExitBodyAction;

    public StationAiBodyWindow()
    {
        RobustXamlLoader.Load(this);

        ExitBodyButton.OnPressed += _ => ExitBodyAction?.Invoke();
    }

    public void UpdateState(StationAiBodyControllerComponent controller)
    {
        BodyList.RemoveAllChildren();
        ExitBodyButton.Disabled = controller.CurrentBody == null;

        if (controller.Bodies.Count == 0)
        {
            BodyList.AddChild(new Label
            {
                Text = Loc.GetString("station-ai-body-window-no-bodies"),
                HorizontalAlignment = HAlignment.Center,
                Margin = new Thickness(0f, 12f),
            });
            return;
        }

        foreach (var body in controller.Bodies)
        {
            BodyList.AddChild(CreateBodyEntry(body));
        }
    }

    /// <summary>
    /// Builds one row in the available AI body list.
    /// </summary>
    private Control CreateBodyEntry(StationAiBodyEntry body)
    {
        var row = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            HorizontalExpand = true,
            SeparationOverride = 6,
        };

        row.AddChild(new Label
        {
            Text = body.Name,
            HorizontalExpand = true,
            VerticalAlignment = VAlignment.Center,
        });

        row.AddChild(new Label
        {
            Text = GetStatusText(body),
            MinWidth = 90,
            VerticalAlignment = VAlignment.Center,
        });

        var button = new Button
        {
            Text = body.IsCurrent
                ? Loc.GetString("station-ai-body-window-current")
                : Loc.GetString("station-ai-body-window-enter"),
            Disabled = body.LinkedAi != null,
            MinWidth = 96,
        };

        button.OnPressed += _ => EnterBodyAction?.Invoke(body.Body);
        row.AddChild(button);

        return row;
    }

    /// <summary>
    /// Returns the localized status text for a body entry.
    /// </summary>
    private static string GetStatusText(StationAiBodyEntry body)
    {
        if (body.IsCurrent)
            return Loc.GetString("station-ai-body-window-status-current");

        return body.LinkedAi == null
            ? Loc.GetString("station-ai-body-window-status-free")
            : Loc.GetString("station-ai-body-window-status-occupied");
    }
}
