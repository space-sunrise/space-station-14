using Content.Shared._Sunrise.Silicons.Borgs;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Localization;

namespace Content.Client._Sunrise.Silicons.Borgs;

[GenerateTypedNameReferences]
public sealed partial class BorgGenderWindow : DefaultWindow
{
    public event Action<BorgGender>? OnGenderSelected;

    public BorgGenderWindow()
    {
        RobustXamlLoader.Load(this);

        Title = Loc.GetString("borg-gender-window-title");

        GenderOptionButton.AddItem(Loc.GetString("borg-gender-male"), (int)BorgGender.Male);
        GenderOptionButton.AddItem(Loc.GetString("borg-gender-female"), (int)BorgGender.Female);
        GenderOptionButton.OnItemSelected += OnGenderOptionSelected;
    }

    public void UpdateState(BorgGenderBuiState state)
    {
        GenderOptionButton.SelectId((int)state.SelectedGender);
    }

    private void OnGenderOptionSelected(OptionButton.ItemSelectedEventArgs args)
    {
        GenderOptionButton.SelectId(args.Id);
        OnGenderSelected?.Invoke((BorgGender)args.Id);
    }
}
