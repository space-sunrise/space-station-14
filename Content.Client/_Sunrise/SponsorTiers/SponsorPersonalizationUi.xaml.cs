using System.Collections.Generic;
using Content.Shared._Sunrise.SunriseCCVars;
using Content.Sunrise.Interfaces.Shared;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Configuration;

namespace Content.Client._Sunrise.SponsorTiers;

[GenerateTypedNameReferences]
public sealed partial class SponsorPersonalizationUi : DefaultWindow
{
    [Dependency] private readonly IConfigurationManager _cfg = default!;
    private readonly ISharedSponsorsManager? _sponsorsManager;

    private List<string> _allowedTitles = [];
    private List<string> _allowedColors = [];

    public SponsorPersonalizationUi()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        IoCManager.Instance!.TryResolveType(out _sponsorsManager);

        UpdateUiState();

        LobbyTtsCheckBox.OnToggled += OnLobbyTtsToggled;
        OocTitleOptionButton.OnItemSelected += OnOocTitleSelected;
        OocColorOptionButton.OnItemSelected += OnOocColorSelected;
    }

    private void UpdateUiState()
    {
        if (_sponsorsManager == null)
            return;

        // TTS Checkbox
        var allowedLobbyTts = _sponsorsManager.ClientAllowedLobbyTts();
        LobbyTtsCheckBox.Visible = allowedLobbyTts;
        if (allowedLobbyTts)
        {
            LobbyTtsCheckBox.Pressed = _cfg.GetCVar(SunriseCCVars.SponsorLobbyTtsEnabled);
        }

        // Titles OptionButton
        _allowedTitles = _sponsorsManager.GetAllowedOocTitles();
        OocTitleOptionButton.Clear();

        // Default "No Title" option
        OocTitleOptionButton.AddItem(Loc.GetString("sponsor-personalization-default"));

        var currentTitle = _cfg.GetCVar(SunriseCCVars.SponsorOocTitle);
        var selectedTitleIndex = 0;

        for (var i = 0; i < _allowedTitles.Count; i++)
        {
            var title = _allowedTitles[i];
            OocTitleOptionButton.AddItem(title);
            if (title == currentTitle)
            {
                selectedTitleIndex = i + 1; // +1 because index 0 is "Default"
            }
        }
        OocTitleOptionButton.SelectId(selectedTitleIndex);
        OocTitleOptionButton.Disabled = _allowedTitles.Count == 0;

        // Colors OptionButton
        _allowedColors = _sponsorsManager.GetAllowedOocColors();
        OocColorOptionButton.Clear();

        // Default "No Color" option
        OocColorOptionButton.AddItem(Loc.GetString("sponsor-personalization-default"));

        var currentColor = _cfg.GetCVar(SunriseCCVars.SponsorOocColor);
        var selectedColorIndex = 0;

        for (var i = 0; i < _allowedColors.Count; i++)
        {
            var color = _allowedColors[i];
            OocColorOptionButton.AddItem(color);
            if (color == currentColor)
            {
                selectedColorIndex = i + 1; // +1 because index 0 is "Default"
            }
        }
        OocColorOptionButton.SelectId(selectedColorIndex);
        OocColorOptionButton.Disabled = _allowedColors.Count == 0;
    }

    private void OnLobbyTtsToggled(BaseButton.ButtonToggledEventArgs args)
    {
        _cfg.SetCVar(SunriseCCVars.SponsorLobbyTtsEnabled, args.Pressed);
    }

    private void OnOocTitleSelected(OptionButton.ItemSelectedEventArgs args)
    {
        OocTitleOptionButton.SelectId(args.Id);
        var value = args.Id == 0 ? string.Empty : _allowedTitles[args.Id - 1];
        _cfg.SetCVar(SunriseCCVars.SponsorOocTitle, value);
    }

    private void OnOocColorSelected(OptionButton.ItemSelectedEventArgs args)
    {
        OocColorOptionButton.SelectId(args.Id);
        var value = args.Id == 0 ? string.Empty : _allowedColors[args.Id - 1];
        _cfg.SetCVar(SunriseCCVars.SponsorOocColor, value);
    }
}
