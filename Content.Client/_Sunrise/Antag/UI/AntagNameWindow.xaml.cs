using Content.Shared._Sunrise.Antag.UI;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Sunrise.Antag.UI;

[GenerateTypedNameReferences]
public sealed partial class AntagNameWindow : DefaultWindow
{
    public Action<string?>? NameConfirmed;
    public Action? RandomKept;

    private int _maxNameLength;

    public AntagNameWindow()
    {
        RobustXamlLoader.Load(this);

        ConfirmButton.OnPressed += _ => ConfirmName();
        RandomButton.OnPressed += _ => RandomKept?.Invoke();
        NameInput.OnTextEntered += _ => ConfirmName();
        NameInput.OnTextChanged += _ => UpdateConfirmButton();
    }

    public void SetState(AntagNameEuiState state)
    {
        _maxNameLength = state.MaxNameLength;
        RoleTitle.Text = Loc.GetString(state.RoleTitle);
        CurrentName.Text = Loc.GetString("antag-name-eui-current", ("name", state.CurrentName));
        NameInput.IsValid = text => text.Length <= _maxNameLength;
        UpdateConfirmButton();
    }

    private void ConfirmName()
    {
        var name = NameInput.Text.Trim();
        if (name.Length == 0 || name.Length > _maxNameLength)
            return;

        NameConfirmed?.Invoke(name);
    }

    private void UpdateConfirmButton()
    {
        var name = NameInput.Text.Trim();
        ConfirmButton.Disabled = name.Length == 0 || name.Length > _maxNameLength;
    }
}
