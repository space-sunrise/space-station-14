using Content.Client.UserInterface.Controls;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Sunrise.Records;

[GenerateTypedNameReferences]
public sealed partial class RecordsPreviewWindow : FancyWindow
{
    public RecordsPreviewWindow()
    {
        RobustXamlLoader.Load(this);
        PreviewTabs.SetTabTitle(0, Loc.GetString("records-medical"));
        PreviewTabs.SetTabTitle(1, Loc.GetString("records-security"));
        PreviewTabs.SetTabTitle(2, Loc.GetString("records-employment"));
        DismissButton.OnPressed += _ => Close();
    }

    public void SetRecords(RecordViewData medical, RecordViewData security, RecordViewData employment, int currentTab)
    {
        MedicalView.SetData(medical);
        SecurityView.SetData(security);
        EmploymentView.SetData(employment);
        PreviewTabs.CurrentTab = currentTab;
    }
}
