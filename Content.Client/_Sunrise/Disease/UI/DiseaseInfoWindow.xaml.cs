using Content.Client.Message;
using Content.Client.UserInterface.Controls;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;
using Robust.Client.UserInterface;
using Robust.Shared.Utility;
using Content.Shared._Sunrise.Disease;

namespace Content.Client._Sunrise.Disease.UI
{
    [GenerateTypedNameReferences]
    public sealed partial class DiseaseInfoWindow : FancyWindow
    {
        public DiseaseInfoWindow()
        {
            RobustXamlLoader.Load(this);
        }

        public void Populate(DiseaseInfoData data)
        {
            // Core Statistics
            BaseChanceLabel.Text = $"{data.BaseInfectChance:F0}%";
            CoughChanceLabel.Text = $"{data.CoughInfectChance:F0}%";
            LethalLabel.Text = data.Lethal.ToString();
            ShieldLabel.Text = data.Shield.ToString();

            // Infection Statistics
            InfectedCountLabel.Text = data.InfectedCount.ToString();
            TotalInfectedLabel.Text = data.TotalInfected.ToString();

            // Resources
            DiseasePointsLabel.Text = data.DiseasePoints.ToString();
        }
    }
}

