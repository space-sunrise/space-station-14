using Content.Client._Sunrise.Records;
using Content.Client.UserInterface.Controls;
using Content.Shared._Sunrise.Records;
using Content.Shared._Sunrise.StationRecords;
using Content.Shared.StationRecords;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Localization;
using Robust.Shared.Prototypes;
using Robust.Shared.Utility;

namespace Content.Client._Sunrise.StationRecords;

[GenerateTypedNameReferences]
public sealed partial class SunriseMedicalRecordsWindow : FancyWindow
{
    public Action<uint>? OnKeySelected;
    public Action<(StationRecordFilterType, string)>? OnFilterChanged;
    public Action<uint>? OnPrintPressed;
    public Action<string, uint>? OnSavePressed;

    private uint? _selectedKey;
    private Dictionary<uint, string> _listing = new();
    private bool _hasAccess;

    public SunriseMedicalRecordsWindow()
    {
        RobustXamlLoader.Load(this);

        SearchBar.OnTextChanged += args =>
            OnFilterChanged?.Invoke((StationRecordFilterType.Name, args.Text));

        RecordListing.OnItemSelected += args =>
        {
            if (RecordListing[args.ItemIndex].Metadata is not uint key)
                return;
            OnKeySelected?.Invoke(key);
        };

        PrintButton.OnPressed += _ =>
        {
            if (_selectedKey is { } key)
                OnPrintPressed?.Invoke(key);
        };

        SaveButton.OnPressed += _ =>
        {
            if (_selectedKey is { } key)
                OnSavePressed?.Invoke(Rope.Collapse(MedicalRecordEdit.TextRope), key);
        };

        MedicalRecordEdit.OnTextChanged += _ =>
            SaveButton.Disabled = !_hasAccess;
    }

    public void UpdateState(SunriseMedicalRecordsConsoleState state)
    {
        _hasAccess = state.HasAccess;

        if (state.RecordListing != null)
        {
            _listing = state.RecordListing;
            RebuildListing();
        }

        if (state.SelectedKey is { } key && state.Record is { } record)
        {
            _selectedKey = key;
            ShowRecord(record, state.HasAccess);
        }
        else
        {
            _selectedKey = null;
            RecordPanel.Visible = false;
            NoRecordLabel.Visible = true;
        }
    }

    private void RebuildListing()
    {
        RecordListing.Clear();
        foreach (var (id, name) in _listing)
        {
            var item = RecordListing.AddItem(name);
            item.Metadata = id;
        }
        RecordListing.SortItemsByText();
    }

    private void ShowRecord(GeneralStationRecord record, bool hasAccess)
    {
        NoRecordLabel.Visible = false;
        RecordPanel.Visible = true;

        RecordName.Text = record.Name;
        RecordJob.Text = record.JobTitle;
        RecordAge.Text = record.Age.ToString();

        var prototypes = IoCManager.Resolve<IPrototypeManager>();
        var loc = IoCManager.Resolve<ILocalizationManager>();
        var identity = RecordIdentityBuilder.FromStationRecord(record, prototypes, loc);
        MedicalView.SetData(RecordViewBuilder.Medical(identity, record.MedicalRecord, loc), showService: false);

        var medical = StructuredCharacterRecords.ReadMedical(record.MedicalRecord);
        MedicalRecordEdit.TextRope = new Rope.Leaf(medical.Notes);
        MedicalRecordEdit.Input.Editable = hasAccess;
        SaveButton.Disabled = !hasAccess;
        PrintButton.Visible = true;
    }
}
