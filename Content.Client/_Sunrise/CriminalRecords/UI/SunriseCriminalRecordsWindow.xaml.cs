using System.Linq;
using Content.Client._Sunrise.Records;
using Content.Shared._Sunrise.CriminalRecords;
using Content.Shared._Sunrise.Laws.Systems;
using Content.Shared._Sunrise.Records;
using Content.Shared.Humanoid.Prototypes;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client._Sunrise.CriminalRecords.UI;

[GenerateTypedNameReferences]
public sealed partial class SunriseCriminalRecordsWindow : DefaultWindow
{
    [Dependency] private readonly IEntityManager _ent = default!;
    [Dependency] private readonly IPrototypeManager _prototypeManager = default!;

    private readonly SharedStationCorporateLawSystem _stationLaw;

    private SunriseCriminalRecordsConsoleBoundUserInterface? _owner;
    private SunriseCriminalRecordsConsoleState? _lastState;

    private SunriseCriminalRecordsDetailsControl? _detailsControl;
    private SunriseCriminalRecordsCaseList? _caseList;
    private SunriseCriminalRecordsCaseEditor? _caseEditor;
    private RecordCardView? _dossierView;
    private ScrollContainer? _dossierScroll;


    public SunriseCriminalRecordsWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        _stationLaw = _ent.System<SharedStationCorporateLawSystem>();

        SearchInput.OnTextChanged += args => RefreshRecordList(args.Text);
        RecordList.OnItemSelected += args =>
        {
            if (args.ItemList[args.ItemIndex].Metadata is uint recordId)
            {
                _owner?.SelectRecord(recordId);
            }
        };
    }

    public void Initialize(SunriseCriminalRecordsConsoleBoundUserInterface owner)
    {
        _owner = owner;
    }

    public void UpdateState(SunriseCriminalRecordsConsoleState state)
    {
        _lastState = state;

        RefreshRecordList(SearchInput.Text);

        if (state.SelectedStationRecord == null)
        {
            foreach (var child in MainContentContainer.Children.ToArray())
            {
                if (child != NoSelectionLabel)
                    child.Dispose();
            }
            NoSelectionLabel.Visible = true;
            _detailsControl = null;
            return;
        }

        NoSelectionLabel.Visible = false;

        if (_detailsControl == null)
        {
            _detailsControl = new SunriseCriminalRecordsDetailsControl();
            _detailsControl.OnStatusChanged += (status, reason) => _owner?.ChangeStatus(status, reason);
            _detailsControl.OnToggleDossier += () => _owner?.SetUIState(
                _lastState?.CurrentUIState == SunriseCriminalRecordsUIState.Dossier
                    ? SunriseCriminalRecordsUIState.List
                    : SunriseCriminalRecordsUIState.Dossier);
            _detailsControl.OnPrintDossier += () => _owner?.PrintDossier();
            MainContentContainer.AddChild(_detailsControl);
        }

        _detailsControl.UpdateInfo(state);

        // Routing logic
        if (state.CurrentUIState == SunriseCriminalRecordsUIState.Editor)
        {
            ShowEditor(state);
        }
        else if (state.CurrentUIState == SunriseCriminalRecordsUIState.Dossier)
        {
            ShowDossier(state);
        }
        else
        {
            ShowCaseList(state);
        }
    }

    private void ShowCaseList(SunriseCriminalRecordsConsoleState state)
    {
        if (_caseList == null)
        {
            _caseList = new SunriseCriminalRecordsCaseList();
            _caseList.OnCreateCase += () => _owner?.CreateCase();
            _caseList.OnEditCase += c => _owner?.SelectCase(c.Id);
        }

        _stationLaw.GetEffectiveLawset(_owner?.Owner, out _, out var articles, out _, out var threshold);

        _caseList.Populate(state.Cases, _prototypeManager, articles, threshold);
        _detailsControl?.SetContent(_caseList);
    }

    private void ShowEditor(SunriseCriminalRecordsConsoleState state)
    {
        if (_caseEditor == null)
        {
            _caseEditor = new SunriseCriminalRecordsCaseEditor();
            _caseEditor.ConsoleEntity = _owner?.Owner;
            _caseEditor.OnBack += () => _owner?.SetUIState(SunriseCriminalRecordsUIState.List);
            _caseEditor.OnSave += (id, laws, circs, notes) => _owner?.UpdateCase(id, laws, circs, notes);
        }

        // Handle case selection: prioritze user selection, then open case, then last case
        var activeCase = state.Cases.Find(c => c.Id == state.SelectedCaseId)
                         ?? state.Cases.FindLast(c => c.Status == CriminalCaseStatus.Open)
                         ?? state.Cases.LastOrDefault();

        if (activeCase != null)
        {
            _caseEditor.OnFinalize = () => _owner?.CloseCase(activeCase.Id);
            _caseEditor.OnReopen = () => _owner?.ReopenCase(activeCase.Id);
            _caseEditor.Setup(activeCase, state.Cases);
        }
        else
            _caseEditor.SetupNew();


        _detailsControl?.SetContent(_caseEditor);
    }

    private void ShowDossier(SunriseCriminalRecordsConsoleState state)
    {
        if (_dossierView == null)
        {
            _dossierView = new RecordCardView();
            _dossierScroll = new ScrollContainer
            {
                HScrollEnabled = false,
                HorizontalExpand = true,
                VerticalExpand = true,
                Children = { _dossierView },
            };
        }

        var noData = Loc.GetString("records-value-no-data");
        var species = state.Species != null && _prototypeManager.TryIndex<SpeciesPrototype>(state.Species, out var speciesProto)
            ? Loc.GetString(speciesProto.Name)
            : noData;
        var isManufactured = state.Species is "Ipc" or "Android";

        var identity = new RecordIdentityData(
            state.SelectedName ?? noData,
            state.JobTitle ?? string.Empty,
            state.Fingerprints ?? noData,
            state.DNA ?? noData,
            string.IsNullOrWhiteSpace(state.FullName) ? state.SelectedName ?? noData : state.FullName,
            Loc.GetString(isManufactured ? "records-date-of-manufacture-edit" : "records-date-of-birth-edit"),
            string.IsNullOrWhiteSpace(state.DateOfBirth) ? noData : state.DateOfBirth,
            state.Gender != null ? Loc.GetString("station-records-gender", ("gender", state.Gender)) : noData,
            species,
            state.Height ?? noData,
            state.Weight ?? noData,
            noData); // Sunrise: ограничения показываются только в медицинском досье, здесь не используются

        _dossierView.SetData(RecordViewBuilder.Security(identity, state.SecurityRecord ?? string.Empty, IoCManager.Resolve<ILocalizationManager>()), showService: false);
        _detailsControl?.SetContent(_dossierScroll!);
    }

    private void RefreshRecordList(string filter = "")
    {
        if (_lastState == null) return;

        RecordList.Clear();
        var filterLower = filter.ToLowerInvariant();

        foreach (var record in _lastState.Records)
        {
            if (!string.IsNullOrEmpty(filterLower))
            {
                string speciesLocalized = record.Species ?? "";
                if (_prototypeManager.TryIndex<SpeciesPrototype>(record.Species ?? "", out var species))
                    speciesLocalized = Loc.GetString(species.Name);

                string genderLocalized = record.Gender != null 
                    ? Loc.GetString("station-records-gender", ("gender", record.Gender)) 
                    : "";

                bool matches = record.Name.ToLowerInvariant().Contains(filterLower) ||
                               (record.DNA?.ToLowerInvariant().Contains(filterLower) ?? false) ||
                               (record.Fingerprints?.ToLowerInvariant().Contains(filterLower) ?? false) ||
                               speciesLocalized.ToLowerInvariant().Contains(filterLower) ||
                               genderLocalized.ToLowerInvariant().Contains(filterLower) ||
                               (record.JobTitle?.ToLowerInvariant().Contains(filterLower) ?? false);

                if (!matches)
                    continue;
            }

            var item = RecordList.AddItem(record.Name);
            item.Metadata = record.Id;
        }
    }
}
