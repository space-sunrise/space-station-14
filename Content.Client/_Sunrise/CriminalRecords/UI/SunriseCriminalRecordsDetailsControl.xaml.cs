using Content.Client.Message;
using Content.Shared.Roles;
using Content.Shared._Sunrise.CriminalRecords;
using Content.Shared.StatusIcon;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client._Sunrise.CriminalRecords.UI;

[GenerateTypedNameReferences]
public sealed partial class SunriseCriminalRecordsDetailsControl : Control
{
    [Dependency] private readonly IPrototypeManager _proto = default!;
    private readonly SpriteSystem _spriteSystem;

    public Action? OnCreateCase;
    public Action<CriminalCase>? OnEditCase;
    public Action<long>? OnSaveCase;
    public Action<long>? OnFinalizeCase;
    public Action? OnCancelEdit;

    public SunriseCriminalRecordsDetailsControl()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        _spriteSystem = IoCManager.Resolve<IEntitySystemManager>().GetEntitySystem<SpriteSystem>();

        VerticalExpand = true;
        HorizontalExpand = true;
    }

    public void UpdateInfo(SunriseCriminalRecordsConsoleState state)
    {
        PersonName.Text = state.SelectedName ?? "Unknown";
        PersonJob.Text = state.JobTitle ?? "Unknown Job";
        AgeLabel.Text = state.Age?.ToString() ?? "??";
        GenderLabel.Text = state.Gender ?? "??";
        DnaLabel.Text = state.DNA ?? "None";
        FingerprintsLabel.Text = state.Fingerprints ?? "None";

    }

    public void SetContent(Control control)
    {
        ContentArea.RemoveAllChildren();
        ContentArea.AddChild(control);
    }
}
